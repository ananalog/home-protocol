using System.Text;

namespace Home.ProtoGen;

/// <summary>Generates c/include/home_proto.h and c/src/home_proto.c.</summary>
public static class CEmitter
{
    public static string TypeName(string structName) => $"hp_{Names.Snake(structName)}_t";
    static string Fn(string structName, string op) => $"hp_{Names.Snake(structName)}_{op}";

    static string CScalar(Scalar s) => s switch
    {
        Scalar.U8 => "uint8_t", Scalar.U16 => "uint16_t", Scalar.U32 => "uint32_t", Scalar.U64 => "uint64_t",
        Scalar.I32 => "int32_t", Scalar.I64 => "int64_t", Scalar.F32 => "float", Scalar.Bool => "bool",
        _ => throw new InvalidOperationException(),
    };

    static string Suffix(Scalar s) => s switch
    {
        Scalar.U8 => "u8", Scalar.U16 => "u16", Scalar.U32 => "u32", Scalar.U64 => "u64",
        Scalar.I32 => "i32", Scalar.I64 => "i64", Scalar.F32 => "f32", Scalar.Bool => "bool",
        Scalar.Str => "str", Scalar.Bytes => "bytes", _ => throw new InvalidOperationException(),
    };

    public static (string header, string source) Emit(Schema s)
    {
        var h = new StringBuilder();
        h.AppendLine("// GENERATED by home-protocol/gen from schema.yaml — do not edit.");
        h.AppendLine("#pragma once");
        h.AppendLine();
        h.AppendLine("#include \"home_tlv.h\"");
        h.AppendLine();
        h.AppendLine("#ifdef __cplusplus");
        h.AppendLine("extern \"C\" {");
        h.AppendLine("#endif");
        h.AppendLine();
        h.AppendLine($"#define HP_PROTO_MAJOR {s.Major}");
        h.AppendLine($"#define HP_PROTO_MINOR {s.Minor}");
        foreach (var (name, value) in s.Constants)
            h.AppendLine(value is string str ? $"#define HP_{name} \"{str}\"" : $"#define HP_{name} {value}");
        h.AppendLine();

        foreach (var e in s.Enums)
        {
            h.AppendLine($"// {e.Name}");
            h.AppendLine("enum {");
            foreach (var (n, v) in e.Values)
                h.AppendLine($"    HP_{Names.UpperSnake(e.Name)}_{n} = {v},");
            h.AppendLine("};");
            h.AppendLine();
        }

        h.AppendLine("// Message types");
        h.AppendLine("enum {");
        foreach (var m in s.Messages)
            h.AppendLine($"    HP_MSG_{m.Name} = 0x{m.Id:X2},");
        h.AppendLine("};");
        h.AppendLine();
        h.AppendLine("const char *hp_msg_name(uint8_t type);");
        h.AppendLine();

        foreach (var st in s.AllBodies())
        {
            h.AppendLine($"typedef struct {{");
            if (st.Fields.Count == 0) h.AppendLine("    uint8_t _unused;");
            foreach (var f in st.Fields)
            {
                var n = f.Name;
                var t = f.Type;
                if (t.IsList)
                {
                    h.AppendLine($"    size_t {n}_count;");
                    if (t.IsStruct) h.AppendLine($"    {TypeName(t.Struct!)} {n}[{f.Max}];");
                    else if (t.Scalar == Scalar.Str) h.AppendLine($"    char {n}[{f.Max}][{f.ItemMax + 1}];");
                    else if (t.Scalar == Scalar.Bytes) throw new InvalidDataException("list<bytes> is not supported");
                    else h.AppendLine($"    {CScalar(t.Scalar!.Value)} {n}[{f.Max}];");
                    continue;
                }
                h.AppendLine($"    bool has_{n};");
                if (t.IsStruct) h.AppendLine($"    {TypeName(t.Struct!)} {n};");
                else if (t.Scalar == Scalar.Str) h.AppendLine($"    char {n}[{f.Max + 1}];");
                else if (t.Scalar == Scalar.Bytes)
                {
                    h.AppendLine($"    const uint8_t *{n};  // points into the decoded buffer (max {f.Max})");
                    h.AppendLine($"    size_t {n}_len;");
                }
                else h.AppendLine($"    {CScalar(t.Scalar!.Value)} {n};");
            }
            h.AppendLine($"}} {TypeName(st.Name)};");
            h.AppendLine();
            h.AppendLine($"void {Fn(st.Name, "write")}(htlv_writer_t *w, const {TypeName(st.Name)} *m);");
            h.AppendLine($"hp_decode_result_t {Fn(st.Name, "read")}({TypeName(st.Name)} *m, const uint8_t *p, size_t n);");
            h.AppendLine();
        }

        h.AppendLine("#ifdef __cplusplus");
        h.AppendLine("}");
        h.AppendLine("#endif");

        var c = new StringBuilder();
        c.AppendLine("// GENERATED by home-protocol/gen from schema.yaml — do not edit.");
        c.AppendLine("#include \"home_proto.h\"");
        c.AppendLine();
        c.AppendLine("#include <string.h>");
        c.AppendLine();
        c.AppendLine("const char *hp_msg_name(uint8_t type)");
        c.AppendLine("{");
        c.AppendLine("    switch (type) {");
        foreach (var m in s.Messages)
            c.AppendLine($"    case HP_MSG_{m.Name}: return \"{m.Name}\";");
        c.AppendLine("    default: return \"?\";");
        c.AppendLine("    }");
        c.AppendLine("}");
        c.AppendLine();

        foreach (var st in s.AllBodies())
        {
            EmitWrite(c, st);
            EmitRead(c, st);
        }
        return (h.ToString(), c.ToString());
    }

    /// <summary>Test helper: decodes a body by message type and re-encodes it (tests/c/roundtrip.gen.c).</summary>
    public static string EmitRoundtrip(Schema s)
    {
        var c = new StringBuilder();
        c.AppendLine("// GENERATED by home-protocol/gen from schema.yaml — do not edit.");
        c.AppendLine("#include <stdlib.h>");
        c.AppendLine("#include \"home_proto.h\"");
        c.AppendLine();
        c.AppendLine("#define RT(T, NAME) do { T *m = calloc(1, sizeof(T)); if (!m) return -1; \\");
        c.AppendLine("    int rc = (int)NAME##_read(m, body, n); if (rc == 0) NAME##_write(w, m); free(m); return rc; } while (0)");
        c.AppendLine();
        c.AppendLine("// kind: 0 request, 1 response, 2 error body. Returns hp_decode_result_t or -2 for an unknown type.");
        c.AppendLine("int hp_test_roundtrip(uint8_t type, int kind, const uint8_t *body, size_t n, htlv_writer_t *w)");
        c.AppendLine("{");
        c.AppendLine("    if (kind == 2) RT(hp_error_body_t, hp_error_body);");
        c.AppendLine("    switch (type) {");
        foreach (var m in s.Messages)
        {
            c.AppendLine($"    case HP_MSG_{m.Name}:");
            c.AppendLine($"        if (kind == 0) RT({TypeName(m.Req.Name)}, hp_{Names.Snake(m.Req.Name)});");
            if (m.Resp != null) c.AppendLine($"        RT({TypeName(m.Resp.Name)}, hp_{Names.Snake(m.Resp.Name)});");
            else c.AppendLine("        return -2;");
        }
        c.AppendLine("    default:");
        c.AppendLine("        return -2;");
        c.AppendLine("    }");
        c.AppendLine("}");
        return c.ToString();
    }

    static void EmitWrite(StringBuilder c, StructDef st)
    {
        c.AppendLine($"void {Fn(st.Name, "write")}(htlv_writer_t *w, const {TypeName(st.Name)} *m)");
        c.AppendLine("{");
        if (st.Fields.Count == 0) c.AppendLine("    (void)w;\n    (void)m;");
        foreach (var f in st.Fields)
        {
            var tag = $"0x{f.WireTag:X2}";
            var t = f.Type;
            if (t.IsList)
            {
                c.AppendLine($"    for (size_t i = 0; i < m->{f.Name}_count && i < {f.Max}; i++) {{");
                if (t.IsStruct)
                {
                    c.AppendLine($"        size_t mark = htlv_w_begin(w, {tag});");
                    c.AppendLine($"        {Fn(t.Struct!, "write")}(w, &m->{f.Name}[i]);");
                    c.AppendLine("        htlv_w_end(w, mark);");
                }
                else c.AppendLine($"        htlv_w_{Suffix(t.Scalar!.Value)}(w, {tag}, m->{f.Name}[i]);");
                c.AppendLine("    }");
                continue;
            }
            c.AppendLine($"    if (m->has_{f.Name}) {{");
            if (t.IsStruct)
            {
                c.AppendLine($"        size_t mark = htlv_w_begin(w, {tag});");
                c.AppendLine($"        {Fn(t.Struct!, "write")}(w, &m->{f.Name});");
                c.AppendLine("        htlv_w_end(w, mark);");
            }
            else if (t.Scalar == Scalar.Bytes)
                c.AppendLine($"        htlv_w_bytes(w, {tag}, m->{f.Name}, m->{f.Name}_len);");
            else
                c.AppendLine($"        htlv_w_{Suffix(t.Scalar!.Value)}(w, {tag}, m->{f.Name});");
            c.AppendLine("    }");
        }
        c.AppendLine("}");
        c.AppendLine();
    }

    static void EmitRead(StringBuilder c, StructDef st)
    {
        c.AppendLine($"hp_decode_result_t {Fn(st.Name, "read")}({TypeName(st.Name)} *m, const uint8_t *p, size_t n)");
        c.AppendLine("{");
        c.AppendLine("    memset(m, 0, sizeof *m);");
        c.AppendLine("    htlv_reader_t r;");
        c.AppendLine("    htlv_r_init(&r, p, n);");
        c.AppendLine("    uint8_t tag;");
        c.AppendLine("    const uint8_t *v;");
        c.AppendLine("    size_t vn;");
        c.AppendLine("    htlv_result_t res;");
        c.AppendLine("    while ((res = htlv_r_next(&r, &tag, &v, &vn)) == HTLV_OK) {");
        c.AppendLine("        switch (tag & 0x7F) {");
        foreach (var f in st.Fields)
        {
            var t = f.Type;
            c.AppendLine($"        case {f.Tag}:");
            if (t.IsList)
            {
                c.AppendLine($"            if (m->{f.Name}_count >= {f.Max}) return HP_DECODE_TOO_LONG;");
                if (t.IsStruct)
                {
                    c.AppendLine($"            {{");
                    c.AppendLine($"                hp_decode_result_t sub = {Fn(t.Struct!, "read")}(&m->{f.Name}[m->{f.Name}_count], v, vn);");
                    c.AppendLine("                if (sub != HP_DECODE_OK) return sub;");
                    c.AppendLine("            }");
                }
                else if (t.Scalar == Scalar.Str)
                    c.AppendLine($"            if (!htlv_get_str(v, vn, m->{f.Name}[m->{f.Name}_count], sizeof m->{f.Name}[0])) return HP_DECODE_TOO_LONG;");
                else
                    c.AppendLine($"            if (!htlv_get_{Suffix(t.Scalar!.Value)}(v, vn, &m->{f.Name}[m->{f.Name}_count])) return HP_DECODE_MALFORMED;");
                c.AppendLine($"            m->{f.Name}_count++;");
                c.AppendLine("            break;");
                continue;
            }
            if (t.IsStruct)
            {
                c.AppendLine("            {");
                c.AppendLine($"                hp_decode_result_t sub = {Fn(t.Struct!, "read")}(&m->{f.Name}, v, vn);");
                c.AppendLine("                if (sub != HP_DECODE_OK) return sub;");
                c.AppendLine("            }");
            }
            else if (t.Scalar == Scalar.Str)
                c.AppendLine($"            if (!htlv_get_str(v, vn, m->{f.Name}, sizeof m->{f.Name})) return HP_DECODE_TOO_LONG;");
            else if (t.Scalar == Scalar.Bytes)
            {
                c.AppendLine($"            if (vn > {f.Max}) return HP_DECODE_TOO_LONG;");
                c.AppendLine($"            m->{f.Name} = v;");
                c.AppendLine($"            m->{f.Name}_len = vn;");
            }
            else
                c.AppendLine($"            if (!htlv_get_{Suffix(t.Scalar!.Value)}(v, vn, &m->{f.Name})) return HP_DECODE_MALFORMED;");
            c.AppendLine($"            m->has_{f.Name} = true;");
            c.AppendLine("            break;");
        }
        c.AppendLine("        default:");
        c.AppendLine("            if (tag & 0x80) return HP_DECODE_UNSUPPORTED;");
        c.AppendLine("            break;");
        c.AppendLine("        }");
        c.AppendLine("    }");
        c.AppendLine("    return res == HTLV_END ? HP_DECODE_OK : HP_DECODE_MALFORMED;");
        c.AppendLine("}");
        c.AppendLine();
    }
}
