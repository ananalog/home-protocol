using System.Text;

namespace Home.ProtoGen;

/// <summary>Generates csharp/Home.Protocol/Generated/Proto.g.cs.</summary>
public static class CSharpEmitter
{
    static string Scalar(Scalar s) => s switch
    {
        ProtoGen.Scalar.U8 => "byte", ProtoGen.Scalar.U16 => "ushort", ProtoGen.Scalar.U32 => "uint",
        ProtoGen.Scalar.U64 => "ulong", ProtoGen.Scalar.I32 => "int", ProtoGen.Scalar.I64 => "long",
        ProtoGen.Scalar.F32 => "float", ProtoGen.Scalar.Bool => "bool", ProtoGen.Scalar.Str => "string",
        ProtoGen.Scalar.Bytes => "byte[]", _ => throw new InvalidOperationException(),
    };

    static string Method(Scalar s) => s switch
    {
        ProtoGen.Scalar.U8 => "U8", ProtoGen.Scalar.U16 => "U16", ProtoGen.Scalar.U32 => "U32",
        ProtoGen.Scalar.U64 => "U64", ProtoGen.Scalar.I32 => "I32", ProtoGen.Scalar.I64 => "I64",
        ProtoGen.Scalar.F32 => "F32", ProtoGen.Scalar.Bool => "Bool", ProtoGen.Scalar.Str => "Str",
        ProtoGen.Scalar.Bytes => "Bytes", _ => throw new InvalidOperationException(),
    };

    static string EnumUnderlying(EnumDef e) => e.Values.Max(v => v.Value) > 255 ? "ushort" : "byte";

    static string ElemType(Field f) =>
        f.Type.IsStruct ? f.Type.Struct! : f.Enum != null ? f.Enum : Scalar(f.Type.Scalar!.Value);

    public static string Emit(Schema s)
    {
        var b = new StringBuilder();
        b.AppendLine("// <auto-generated> by home-protocol/gen from schema.yaml — do not edit. </auto-generated>");
        b.AppendLine("#nullable enable");
        b.AppendLine("namespace Home.Protocol;");
        b.AppendLine();
        b.AppendLine("public static class ProtoInfo");
        b.AppendLine("{");
        b.AppendLine($"    public const int Major = {s.Major};");
        b.AppendLine($"    public const int Minor = {s.Minor};");
        foreach (var (name, value) in s.Constants)
            b.AppendLine(value is string str
                ? $"    public const string {Names.Pascal(name)} = \"{str}\";"
                : $"    public const int {Names.Pascal(name)} = {value};");
        b.AppendLine("}");
        b.AppendLine();

        foreach (var e in s.Enums)
        {
            if (e.IsFlags) b.AppendLine("[System.Flags]");
            b.AppendLine($"public enum {e.Name} : {EnumUnderlying(e)}");
            b.AppendLine("{");
            foreach (var (n, v) in e.Values) b.AppendLine($"    {Names.Pascal(n)} = {v},");
            b.AppendLine("}");
            b.AppendLine();
        }

        b.AppendLine("public enum MsgType : byte");
        b.AppendLine("{");
        foreach (var m in s.Messages) b.AppendLine($"    {Names.Pascal(m.Name)} = 0x{m.Id:X2},");
        b.AppendLine("}");
        b.AppendLine();

        foreach (var st in s.Structs) EmitClass(b, s, st, null, false);
        foreach (var m in s.Messages)
        {
            EmitClass(b, s, m.Req, m, false);
            if (m.Resp != null) EmitClass(b, s, m.Resp, m, true);
        }

        b.AppendLine("public static class Messages");
        b.AppendLine("{");
        b.AppendLine("    public static IProtoMessage? ReadRequest(MsgType type, System.ReadOnlySpan<byte> body) => type switch");
        b.AppendLine("    {");
        foreach (var m in s.Messages) b.AppendLine($"        MsgType.{Names.Pascal(m.Name)} => {m.Req.Name}.Read(body),");
        b.AppendLine("        _ => null,");
        b.AppendLine("    };");
        b.AppendLine();
        b.AppendLine("    public static IProtoMessage? ReadResponse(MsgType type, System.ReadOnlySpan<byte> body) => type switch");
        b.AppendLine("    {");
        foreach (var m in s.Messages.Where(m => m.Resp != null))
            b.AppendLine($"        MsgType.{Names.Pascal(m.Name)} => {m.Resp!.Name}.Read(body),");
        b.AppendLine("        _ => null,");
        b.AppendLine("    };");
        b.AppendLine();
        b.AppendLine("    public static bool HasResponse(MsgType type) => type switch");
        b.AppendLine("    {");
        foreach (var m in s.Messages.Where(m => m.Resp != null))
            b.AppendLine($"        MsgType.{Names.Pascal(m.Name)} => true,");
        b.AppendLine("        _ => false,");
        b.AppendLine("    };");
        b.AppendLine("}");
        return b.ToString();
    }

    static void EmitClass(StringBuilder b, Schema s, StructDef st, MessageDef? msg, bool isResp)
    {
        var iface = msg != null ? "IProtoMessage" : "IProtoBody";
        b.AppendLine($"public sealed partial class {st.Name} : {iface}");
        b.AppendLine("{");
        if (msg != null)
        {
            b.AppendLine($"    public MsgType Type => MsgType.{Names.Pascal(msg.Name)};");
            b.AppendLine($"    public bool IsResponse => {(isResp ? "true" : "false")};");
            b.AppendLine();
        }
        foreach (var f in st.Fields)
        {
            var prop = Names.Pascal(f.Name);
            if (f.Type.IsList)
                b.AppendLine($"    public System.Collections.Generic.List<{ElemType(f)}> {prop} {{ get; set; }} = new();");
            else
                b.AppendLine($"    public {ElemType(f)}? {prop} {{ get; set; }}");
        }
        if (st.Fields.Count > 0) b.AppendLine();

        // Write
        b.AppendLine("    public void Write(TlvWriter w)");
        b.AppendLine("    {");
        foreach (var f in st.Fields)
        {
            var prop = Names.Pascal(f.Name);
            var tag = $"0x{f.WireTag:X2}";
            if (f.Type.IsList)
            {
                b.AppendLine($"        if ({prop}.Count > {f.Max}) throw new ProtoException(ErrorCode.InvalidValue, \"{st.Name}.{prop}: more than {f.Max} items\");");
                b.AppendLine($"        foreach (var x in {prop}) {WriteExpr(f, "x", tag, f.Type.Scalar == ProtoGen.Scalar.Str ? f.ItemMax : f.Max)};");
            }
            else
            {
                var val = f.Type.IsStruct || f.Type.Scalar is ProtoGen.Scalar.Str or ProtoGen.Scalar.Bytes ? prop : $"{prop}.Value";
                b.AppendLine($"        if ({prop} != null) {WriteExpr(f, val, tag, f.Max)};");
            }
        }
        b.AppendLine("    }");
        b.AppendLine();

        // Read
        b.AppendLine($"    public static {st.Name} Read(System.ReadOnlySpan<byte> data)");
        b.AppendLine("    {");
        b.AppendLine($"        var m = new {st.Name}();");
        b.AppendLine("        var r = new TlvReader(data);");
        b.AppendLine("        while (r.Next(out var tag, out var v))");
        b.AppendLine("        {");
        b.AppendLine("            switch (tag & 0x7F)");
        b.AppendLine("            {");
        foreach (var f in st.Fields)
        {
            var prop = Names.Pascal(f.Name);
            var expr = ReadExpr(f, "v");
            b.AppendLine(f.Type.IsList
                ? $"                case {f.Tag}: m.{prop}.Add({expr}); break;"
                : $"                case {f.Tag}: m.{prop} = {expr}; break;");
        }
        b.AppendLine("                default: Tlv.Unknown(tag); break;");
        b.AppendLine("            }");
        b.AppendLine("        }");
        b.AppendLine("        return m;");
        b.AppendLine("    }");
        b.AppendLine("}");
        b.AppendLine();
    }

    static string WriteExpr(Field f, string val, string tag, int max)
    {
        if (f.Type.IsStruct) return $"w.Struct({tag}, {val})";
        var sc = f.Type.Scalar!.Value;
        if (sc is ProtoGen.Scalar.Str or ProtoGen.Scalar.Bytes) return $"w.{Method(sc)}({tag}, {val}, {max})";
        if (f.Enum != null) return $"w.{Method(sc)}({tag}, ({Scalar(sc)}){val})";
        return $"w.{Method(sc)}({tag}, {val})";
    }

    static string ReadExpr(Field f, string v)
    {
        if (f.Type.IsStruct) return $"{f.Type.Struct}.Read({v})";
        var sc = f.Type.Scalar!.Value;
        var e = $"Tlv.{Method(sc)}({v})";
        return f.Enum != null ? $"({f.Enum}){e}" : e;
    }
}
