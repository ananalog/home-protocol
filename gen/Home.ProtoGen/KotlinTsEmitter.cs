using System.Text;

namespace Home.ProtoGen;

/// <summary>Generates kotlin/.../Proto.kt.</summary>
public static class KotlinEmitter
{
    static string KType(Scalar s) => s switch
    {
        Scalar.U8 or Scalar.U16 or Scalar.I32 => "Int",
        Scalar.U32 or Scalar.U64 or Scalar.I64 => "Long",
        Scalar.F32 => "Float", Scalar.Bool => "Boolean", Scalar.Str => "String", Scalar.Bytes => "ByteArray",
        _ => throw new InvalidOperationException(),
    };

    static string M(Scalar s) => s.ToString().ToLowerInvariant();

    static string ElemType(Field f) => f.Type.IsStruct ? f.Type.Struct! : KType(f.Type.Scalar!.Value);

    public static string Emit(Schema s)
    {
        var b = new StringBuilder();
        b.AppendLine("// GENERATED by home-protocol/gen from schema.yaml — do not edit.");
        b.AppendLine("@file:Suppress(\"unused\", \"RedundantVisibilityModifier\")");
        b.AppendLine();
        b.AppendLine("package home.protocol");
        b.AppendLine();
        b.AppendLine("object Proto {");
        b.AppendLine($"    const val MAJOR = {s.Major}");
        b.AppendLine($"    const val MINOR = {s.Minor}");
        foreach (var (name, value) in s.Constants)
            b.AppendLine(value is string str ? $"    const val {name} = \"{str}\"" : $"    const val {name} = {value}");
        b.AppendLine("}");
        b.AppendLine();
        foreach (var e in s.Enums)
        {
            b.AppendLine($"object {e.Name} {{");
            foreach (var (n, v) in e.Values) b.AppendLine($"    const val {n} = {v}");
            b.AppendLine($"    fun name(v: Int): String = when (v) {{");
            foreach (var (n, v) in e.Values) b.AppendLine($"        {v} -> \"{n}\"");
            b.AppendLine("        else -> v.toString()");
            b.AppendLine("    }");
            b.AppendLine("}");
            b.AppendLine();
        }
        b.AppendLine("object MsgType {");
        foreach (var m in s.Messages) b.AppendLine($"    const val {m.Name} = 0x{m.Id:X2}");
        b.AppendLine("}");
        b.AppendLine();

        foreach (var st in s.Structs) EmitClass(b, st, null, false);
        foreach (var m in s.Messages)
        {
            EmitClass(b, m.Req, m, false);
            if (m.Resp != null) EmitClass(b, m.Resp, m, true);
        }

        b.AppendLine("object Messages {");
        b.AppendLine("    fun readRequest(type: Int, data: ByteArray, off: Int, end: Int): ProtoMessage? = when (type) {");
        foreach (var m in s.Messages) b.AppendLine($"        MsgType.{m.Name} -> {m.Req.Name}.read(data, off, end)");
        b.AppendLine("        else -> null");
        b.AppendLine("    }");
        b.AppendLine();
        b.AppendLine("    fun readResponse(type: Int, data: ByteArray, off: Int, end: Int): ProtoMessage? = when (type) {");
        foreach (var m in s.Messages.Where(m => m.Resp != null)) b.AppendLine($"        MsgType.{m.Name} -> {m.Resp!.Name}.read(data, off, end)");
        b.AppendLine("        else -> null");
        b.AppendLine("    }");
        b.AppendLine("}");
        return b.ToString();
    }

    static void EmitClass(StringBuilder b, StructDef st, MessageDef? msg, bool isResp)
    {
        b.AppendLine($"class {st.Name} : {(msg != null ? "ProtoMessage" : "ProtoBody")} {{");
        if (msg != null)
        {
            b.AppendLine($"    override val msgType: Int get() = MsgType.{msg.Name}");
            b.AppendLine($"    override val isResponse: Boolean get() = {(isResp ? "true" : "false")}");
        }
        foreach (var f in st.Fields)
        {
            var p = Names.Camel(f.Name);
            b.AppendLine(f.Type.IsList
                ? $"    var {p}: MutableList<{ElemType(f)}> = mutableListOf()"
                : $"    var {p}: {ElemType(f)}? = null");
        }
        b.AppendLine();
        b.AppendLine("    override fun write(w: TlvWriter) {");
        foreach (var f in st.Fields)
        {
            var p = Names.Camel(f.Name);
            var tag = $"0x{f.WireTag:X2}";
            if (f.Type.IsList)
            {
                b.AppendLine($"        if ({p}.size > {f.Max}) throw ProtoException(ErrorCode.INVALID_VALUE, \"{st.Name}.{p}: more than {f.Max} items\")");
                b.AppendLine($"        for (x in {p}) {WriteExpr(f, "x", tag, f.Type.Scalar == Scalar.Str ? f.ItemMax : f.Max)}");
            }
            else b.AppendLine($"        {p}?.let {{ {WriteExpr(f, "it", tag, f.Max)} }}");
        }
        b.AppendLine("    }");
        b.AppendLine();
        b.AppendLine("    companion object {");
        b.AppendLine($"        fun read(data: ByteArray, off: Int = 0, end: Int = data.size): {st.Name} {{");
        b.AppendLine($"            val m = {st.Name}()");
        b.AppendLine("            val r = TlvReader(data, off, end)");
        b.AppendLine("            while (r.next()) {");
        b.AppendLine("                when (r.tag and 0x7F) {");
        foreach (var f in st.Fields)
        {
            var p = Names.Camel(f.Name);
            var e = f.Type.IsStruct ? $"r.struct({f.Type.Struct}::read)" : $"r.{M(f.Type.Scalar!.Value)}()";
            b.AppendLine(f.Type.IsList ? $"                    {f.Tag} -> m.{p}.add({e})" : $"                    {f.Tag} -> m.{p} = {e}");
        }
        b.AppendLine("                    else -> r.unknown()");
        b.AppendLine("                }");
        b.AppendLine("            }");
        b.AppendLine("            return m");
        b.AppendLine("        }");
        b.AppendLine("    }");
        b.AppendLine("}");
        b.AppendLine();
    }

    static string WriteExpr(Field f, string v, string tag, int max)
    {
        if (f.Type.IsStruct) return $"w.struct({tag}, {v})";
        var sc = f.Type.Scalar!.Value;
        return sc is Scalar.Str or Scalar.Bytes ? $"w.{M(sc)}({tag}, {v}, {max})" : $"w.{M(sc)}({tag}, {v})";
    }
}

/// <summary>Generates ts/home_proto.ts — constants only (the Mini App talks JSON to the server).</summary>
public static class TsEmitter
{
    public static string Emit(Schema s)
    {
        var b = new StringBuilder();
        b.AppendLine("// GENERATED by home-protocol/gen from schema.yaml — do not edit.");
        b.AppendLine($"export const PROTO_MAJOR = {s.Major};");
        b.AppendLine($"export const PROTO_MINOR = {s.Minor};");
        b.AppendLine();
        foreach (var e in s.Enums)
        {
            b.AppendLine($"export const {e.Name} = {{");
            foreach (var (n, v) in e.Values) b.AppendLine($"  {n}: {v},");
            b.AppendLine("} as const;");
            b.AppendLine($"export type {e.Name} = (typeof {e.Name})[keyof typeof {e.Name}];");
            b.AppendLine();
        }
        b.AppendLine("export const MsgType = {");
        foreach (var m in s.Messages) b.AppendLine($"  {m.Name}: 0x{m.Id:X2},");
        b.AppendLine("} as const;");
        return b.ToString();
    }
}
